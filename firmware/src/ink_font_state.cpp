const uint8_t* inkStateGlyph(char c, int* w)
{
  for (int i = 0; i < INK_STATE_COUNT; i++) {
    if (INK_STATE_CHARS[i] == c) {
      if (w) *w = INK_STATE_WIDTHS[i];
      return &INK_STATE_DATA[INK_STATE_OFFSETS[i]];
    }
  }
  if (w) *w = 0;
  return 0;
}
